namespace D2.Data.Ui;

/// <summary>
/// Курсор окна из разметки (<c>docs/ui-windows.md</c>, «Курсор окна»). Строка <c>DIALOG</c>: поле 6 — имя картинки, поля 7–8 — горячая
/// точка от левого верхнего угла картинки (разбор <c>0x50ca59</c>: имя есть — два «%ld»). Имя берётся как есть, без приставки окна
/// (<c>0x50aa3b</c> — простое копирование): у всех окон игры это <c>_CUDEFAUL</c> — кинжал из <c>Interf.ff</c> (холст 321×321, кинжал
/// в левом верхнем углу) с точкой 0,0. Картинки <c>DLG_*_CUDEFAUL</c> архивов движок не берёт. Сборка окна (<c>0x50cd54</c>) делает из
/// картинки курсор (<c>0x532df9</c>) и отдаёт его окну (<c>CInterface::setCursor</c>, место <c>+0x74</c> → <c>0x5308aa</c>).
///
/// <para>Какой курсор виден (<c>CCursorImpl</c> <c>0x54021c</c>, по движению мыши <c>0x540175</c>): курсор, заданный поверх всего
/// (тащение), иначе верхний интерфейс менеджера (<c>0x53ca03</c>) отвечает за точку (<c>0x5308d5</c>): самый глубокий потомок под мышью
/// со своим курсором, иначе свой. Значит, пока окно открыто — его курсор над всем экраном, окно поверх окна — курсор верхнего, окно
/// закрылось — снова отвечает карта или меню под ним. Нет курсора ни у кого — курсор не меняется (<c>0x5401c7</c>).</para>
/// </summary>
public readonly record struct UiCursor(string Frame, int HotspotX, int HotspotY)
{
    /// <summary>Курсор экрана; у экрана без курсора (панели, столица, ролик) — null: курсор остаётся прежним.</summary>
    public static UiCursor? Of(UiScreen? screen)
    {
        if (screen is null || screen.Cursor.Length == 0) return null;
        // Поля 7–8 лежат первыми в Legacy; у своего экрана без них — левый верхний угол.
        return screen.Legacy is [var x, var y, ..] && int.TryParse(x, out int hx) && int.TryParse(y, out int hy)
            ? new UiCursor(screen.Cursor, hx, hy)
            : new UiCursor(screen.Cursor, 0, 0);
    }
}
