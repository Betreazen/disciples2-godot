namespace D2.Data.Ui;

/// <summary>Как картинка ложится в место своего элемента (<see cref="UiScreenState.SetImage"/>).</summary>
public enum UiImageAlign
{
    /// <summary>От левого верхнего угла; шире места — вписывается по ширине, низ за местом обрезается (значки рас сценария:
    /// картинка 174×202 в месте 45×73, сверено пользователем по снимкам 19.09).</summary>
    Fit,

    /// <summary>По центру места без масштаба, в обе стороны (флаги 1|8 <c>setImage</c> <c>0x530e29</c>; попап события и журнал
    /// кладут картинку 350×450 в место 330×430 — на 10 точек левее и выше угла, снимки «Задания» 28.09).</summary>
    Center,

    /// <summary>От левого верхнего угла без масштаба, что за местом — обрезается (картинка лавки <c>SITE0002</c>/<c>SITE0003</c> 260×248 в
    /// месте <c>IMG_MERCHANT</c> 260×219: движок кладёт её точкой (0, 0) — <c>0x49938e</c> → <c>0x530db8</c>; у оригинала она в рамке не
    /// выходит, у порта выходила на 29 точек вниз — снимок пользователя «Лавка Веррика» 17.10). Ранг 2: обрезку движка по месту элемента
    /// листингом не дочитали (<c>0x53e050</c> кладёт картинку в список показа элемента).</summary>
    Clip,
}

public static class UiImagePlacement
{
    /// <summary>Сдвиг картинки от угла места: у движка — (место − картинка) / 2 с отбрасыванием дробной части к нулю
    /// (<c>cdq; sub; sar 1</c>).</summary>
    public static (int X, int Y) Offset(UiImageAlign align, int placeWidth, int placeHeight, int width, int height) =>
        align == UiImageAlign.Center ? ((placeWidth - width) / 2, (placeHeight - height) / 2) : (0, 0);
}
