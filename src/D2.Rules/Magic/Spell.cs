using D2.Rules.Map;

namespace D2.Rules.Magic;

/// <summary>Категория заклинания — <c>Gspells.CATEGORY</c>.
/// <para><b>Ранг 1: перечень взят из самой игры</b> — <c>Globals/Lspell.dbf</c>, двенадцать строк
/// (<c>0 L_ATTACK … 12 L_GIVE_WARDS</c>, значения 5 нет). Тулсет здесь не источник, а совпадение.</para>
/// <para><b>Ранг 1 по данным: категория — это не подпись, а рабочая колонка.</b> Кросс-таблица
/// «категория × заполненные колонки» по всем 120 живым строкам ванили сходится один в один, без
/// единого исключения, кроме одного honest-случая (<c>g000ss0100</c> «Swift», см. ниже):</para>
/// <list type="table">
/// <item><term>0 Attack (33)</term><description><c>DAMAGE_QTY</c> и <c>DAMAGE_SRC</c> заполнены у всех 33</description></item>
/// <item><term>1 Lower (20)</term><description><c>MODIF_ID</c> у всех 20</description></item>
/// <item><term>2 Heal (7)</term><description><c>HEAL_QTY</c> у всех 7</description></item>
/// <item><term>3 Boost (25)</term><description><c>MODIF_ID</c> у всех 25</description></item>
/// <item><term>4 Summon (19)</term><description><c>UNIT_ID</c> у всех 19</description></item>
/// <item><term>6 Fog (4), 7 Unfog (3), 9 Invisibility (2), 10 RemoveRod (1)</term>
///       <description>ни одной колонки полезной нагрузки — эффект несёт сама категория</description></item>
/// <item><term>8 RestoreMove (4)</term><description><c>RESTORE_M</c> у всех 4; у одного
///       (<c>g000ss0100</c> «Swift») <b>вдобавок</b> <c>MODIF_ID</c> — <c>TYPE 7</c> MoveAllowance
///       +30 %. То есть у заклинания бывает <b>больше одного</b> эффекта, и раскладывать его надо
///       по заполненным колонкам, а не по категории</description></item>
/// <item><term>11 ChangeTerrain (2)</term><description><c>GROUND_CAT</c> = 1 (лес) у обоих —
///       «Create Grove» и «Create Forest»</description></item>
/// <item><term>12 GiveWards</term><description>в ванили ноль строк</description></item>
/// </list>
/// <para><b>Что это опровергает.</b> ТЗ задачи называло переключателем смены террейна колонку
/// <c>CHNGTERCAT</c>. Данные говорят обратное: <c>CHNGTERCAT</c> — логическое поле (тип <c>L</c>,
/// один байт; в движке читается булевым читателем <c>0x595a36</c>, поле <c>+0x74</c> записи), и оно
/// <b>ложно у всех 120 строк ванили</b>. Смену террейна несёт <see cref="ChangeTerrain"/> плюс
/// <c>GROUND_CAT</c>. Правило фазы «колонку опознаёт распределение её значений, а не её имя»
/// сработало ровно здесь.</para></summary>
public enum SpellCategory
{
    Attack = 0,
    Lower = 1,
    Heal = 2,
    Boost = 3,
    Summon = 4,
    Fog = 6,
    Unfog = 7,
    RestoreMove = 8,
    Invisibility = 9,

    /// <summary>Снятие жезла («Sinkhole» <c>g000ss0119</c>, единственное в ванили) —
    /// <see cref="SpellCast.RemoveRod"/>: свой жезл своим заклинанием не сносится, штрафа
    /// <c>D_ROD</c> нет, земля замерзает (задача 8 Ф7).</summary>
    RemoveRod = 10,
    ChangeTerrain = 11,
    GiveWards = 12,
}

/// <summary>Заклинание — строка <c>Gspells.dbf</c> глазами правил.
///
/// <para><b>Все 120 вани́льных заклинаний — заклинания КАРТЫ, а не боя.</b> Это не упрощение
/// модели, а измерение, и оно расходится с формулировкой плана Ф6 («боевые заклинания идут через
/// <c>CBatAttack</c> и видны как <c>attack_new</c>»). Основания, все ранга 1:
/// <list type="number">
/// <item>В записи заклинания <b>нет поля атаки вовсе</b>. Загрузчик <c>Gspells</c> (GOG
/// <c>0x5822e1</c>-<c>0x5824a6</c>, прочитан целиком) кладёт девятнадцать колонок в девятнадцать
/// полей, и боевого среди них два: <c>DAMAGE_SRC</c> (<c>+0x60</c>, источник атаки) и
/// <c>DAMAGE_QTY</c> (<c>+0x5c</c>, число). Ссылки на <c>Gattacks</c> нет ни одной, а
/// <c>createBatAttack</c> (GOG <c>0x644b3e</c>) строит класс атаки именно по ней.</item>
/// <item>Категории (<c>Lspell.dbf</c>) — понятия карты целиком: туман, снятие тумана,
/// невидимость, возврат очков хода, смена земли, снятие жезла.</item>
/// <item><c>RESTORE_M</c> — очки хода отряда, величина карты; в бою их нет.</item>
/// </list>
/// Практический вывод для Ф6: ветвь «боевые заклинания» <b>пуста</b>, и событие <c>attack_new</c>
/// корпуса v4 заклинаний не покажет никогда — не потому, что зонд слеп, а потому, что заклинание
/// не проходит через <c>CBatAttack</c>. Проверяется это диффом <c>.sg</c>
/// (<c>MidSpellCast</c> <c>Sg.g.cs:3274</c>, <c>MidSpellEffects</c> <c>:3374</c>,
/// <c>PlayerKnownSpells</c> <c>:4212</c>), а не журналом боя.</para>
///
/// <para><b>Кто и когда кастует — не здесь.</b> Выбор цели и решение применить заклинание — политика
/// ИИ, то есть Ф7. Здесь моделируется только применение: во что заклинание обходится, куда достаёт
/// и что делает.</para>
///
/// <para><b>Раскладка полей записи движка</b> (ранг 1, тот же загрузчик; совпала с
/// <c>TStrategicSpellData</c> тулсета поле в поле, то есть чужой реверс здесь подтверждение, а не
/// источник): <c>CATEGORY +0</c>, <c>AI_CAT +0xc</c>, <c>NAME_TXT +0x18</c>, <c>DESC_TXT +0x20</c>,
/// <c>MODIF_TXT +0x28</c>, <c>LEVEL +0x30</c>, <c>CASTING_C +0x34</c>, <c>BUY_C +0x40</c>,
/// <c>UNIT_ID +0x4c</c>, <c>MODIF_ID +0x50</c>, <c>RESTORE_M +0x54</c>, <c>AREA +0x58</c>,
/// <c>DAMAGE_QTY +0x5c</c>, <c>DAMAGE_SRC +0x60</c>, <c>HEAL_QTY +0x64</c>, <c>GROUND_CAT +0x68</c>,
/// <c>CHNGTERCAT +0x74</c>, <c>WARD1..4 +0x78</c>.</para>
///
/// <para><c>NAME_TXT</c>, <c>DESC_TXT</c>, <c>MODIF_TXT</c> и <c>AI_CAT</c> сюда не взяты: первые три
/// — тексты для игрока, четвёртая (<c>LAiSpellCategory</c>: All/None/Human/Undead/Heretic/Dwarf) —
/// подсказка выбора для ИИ, то есть Ф7.</para></summary>
/// <param name="CastingCost">Цена применения — <b>та же строковая казна</b>
/// <c>g0000:r0000:y0100:e0000:w0000[:b0000]</c>, что у дохода расы и цены постройки, а не «пять
/// ресурсов» собственного формата. Разбор — <see cref="Bank.Parse"/>, дублировать его не нужно.
/// <para><b>Ранг 1, дизассемблер GOG.</b> Колонки <c>CASTING_C</c> и <c>BUY_C</c> читаются одним
/// банковым читателем (<c>0x595adf</c>), тот отдаёт строку в разбор <c>0x5862cb</c>, а тот шесть раз
/// зовёт разбор одной валюты <c>0x5863c5</c>. Правила разбора, прочитанные до <c>ret</c>:
/// <list type="bullet">
/// <item>вся строка сперва поднимается в верхний регистр (<c>_strupr</c>, <c>0x5862f0</c>) — регистр
/// не важен;</item>
/// <item>буквы валют лежат таблицей из шести байт по <c>0x6e8040</c>: <c>"GRYEWB"</c> — золото,
/// инфернальная, жизни, смерти, руническая, рощи;</item>
/// <item>валюта ищется по букве (<c>strchr</c>), поэтому <b>порядок частей не навязан</b>;</item>
/// <item>после буквы обязаны стоять <b>ровно четыре</b> цифры до ближайшего <c>':'</c> или конца
/// строки (<c>0x586421</c>: <c>cmp eax, 4</c>), каждая проверяется <c>isdigit</c>, величина берётся
/// <c>atoi</c> и кладётся <b>16-битным</b> словом;</item>
/// <item>шестая валюта (<c>B</c>, мана рощи) читается <b>только если</b> длина строки больше 29
/// (<c>0x58637c</c>: <c>cmp eax, 0x1d</c>), иначе поле обнуляется. Ровно это и видно в данных:
/// 96 строк <c>Gspells</c> длиной 29 (пять валют) и 24 длиной 35 (шесть);</item>
/// <item>любая неудача — не ноль, а <b>10000 в каждой из шести</b> валют (<c>0x5863a1</c>:
/// <c>mov eax, 0x2710</c>): признак «казна не разобрана».</item>
/// </list>
/// Запись движка — шесть <c>int16</c>, двенадцать байт (копирование <c>0x586290</c>: шесть
/// <c>mov word</c>; и расстояние между полями записи заклинания <c>0x40 − 0x34 = 0xc</c>). Наша
/// <see cref="Bank"/> хранит <c>long</c> и не требует четырёх цифр — на вани́льных данных это
/// неразличимо (тест проверяет, что все 240 строк цены удовлетворяют движковому правилу), а на
/// испорченных мод-данных наш разбор мягче.
/// <para>В ванили золото в <c>CASTING_C</c> не встречается ни разу (применение стоит только маны), а
/// <c>BUY_C</c> — наоборот, всегда ровно одно золото.</para></param>
/// <param name="Area">Размер области в клетках, <b>не</b> идентификатор категории. Ранг 1: движок
/// читает эту колонку общим читателем целого (<c>0x5959f1</c>) с границами
/// <c>0x80000000..0x7fffffff</c> (<c>0x5823f5</c>), то есть без таблицы категорий и без подрезки —
/// в отличие от соседних <c>DAMAGE_SRC</c> и <c>GROUND_CAT</c>, которые читаются <b>категорийными</b>
/// читателями (<c>0x582f3b</c>, <c>0x582f8c</c>) с дескриптором <c>L</c>-таблицы. В ванили значения
/// 1 (95 штук), 3, 5, 7, 9 и 999 (6). 999 — не признак и не константа: во всём сегменте кода нет ни
/// одного сравнения с <c>0x3e7</c>, число просто больше любой карты. Геометрия области —
/// <see cref="SpellCast.Tiles"/>.</param>
/// <param name="RestoreMovePercent">Сколько <b>процентов</b> очков хода возвращает заклинание, а не
/// сколько маны оно восстанавливает. Колонка называется <c>RESTORE_M</c>, и задача 1 прочла её как
/// <c>RestoreMana</c> — это третья подпись фазы, разошедшаяся с данными; имя исправлено задачей 10
/// вместе с переселением записи в <c>SpellLoader.Load</c>.
/// <b>Ранг 1 по текстам самой игры</b> (<c>Tglobal.dbf</c>, описания всех четырёх строк категории
/// <see cref="SpellCategory.RestoreMove"/>): <c>g000ss0006</c> «Haste» при <c>RESTORE_M</c> = 50 —
/// «Hasted units recover <b>50 %</b> of their move points», <c>g000ss0032</c> 100 — «100 % of their
/// moving points», <c>g000ss0100</c> 30 — «30 %», <c>g000ss0087</c> 100 — «All the caster's units
/// recover 100 %». Поле движка на <c>+0x54</c>, тулсет зовёт его <c>restoreMovePoints</c>.
/// Величины ванили — 30, 50, 100, 100.</param>
/// <param name="DamageSource">Источник урона, <c>LattS.dbf</c> (0 Weapon … 7 Air). У 33 боевых
/// заклинаний ванили встречаются шесть источников — Mind (3), Death (5), Fire (7), Water (6),
/// Earth (7), Air (5); Weapon и Life не встречаются ни разу. Осмыслен только вместе с ненулевым
/// <paramref name="DamageQty"/>.</param>
/// <param name="Ground">Земля, которую создаёт заклинание, <c>Lground.dbf</c> (0 Plain, 1 Forest,
/// 3 Water, 4 Mountain). Осмыслен только при <see cref="SpellCategory.ChangeTerrain"/>: ноль —
/// законное значение (равнина), поэтому «есть ли эффект» решает категория, а не величина.</param>
public sealed record Spell(
    string Id,
    SpellCategory Category,
    int Level,
    Bank CastingCost,
    Bank BuyCost,
    int Area,
    string ModifierId,
    string SummonUnitId,
    int RestoreMovePercent,
    int DamageSource,
    int DamageQty,
    int HealQty,
    int Ground,
    IReadOnlyList<string> Wards)
{
    /// <summary>Границы уровня заклинания, которые проверяет сам движок. <b>Ранг 1:</b> читатель
    /// колонки <c>LEVEL</c> (GOG <c>0x58250f</c>) после разбора сравнивает величину с двумя
    /// глобальными переменными — <c>[0x6e9398]</c> = 1 и <c>[0x6e939c]</c> = 5 — и на выходе за
    /// границы зовёт репортёр ошибки таблицы (<c>0x595870</c>). Данные согласны: 25 + 25 + 25 + 25
    /// + 20 строк по уровням 1..5.</summary>
    public const int MinLevel = 1;
    public const int MaxLevel = 5;

    /// <summary>Площадь «вся карта»: признак <c>0x582b5a</c> сравнивает <c>AREA</c> с <c>[0x6e93a8]</c> = 999.</summary>
    public const int WholeMapArea = 999;

    /// <summary>Радиус области в клетках: <c>(Area − 1) / 2</c>. Для <c>Area = 1</c> — 0, то есть
    /// одна клетка цели.</summary>
    public int AreaRadius => (Area - 1) / 2;
}
