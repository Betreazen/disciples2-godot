using D2.Rules.Map;

namespace D2.Rules.Magic;

/// <summary>Категория предмета — <c>GItem.ITEM_CAT</c>.
///
/// <para><b>Ранг 1: перечень взят из самой игры</b> — <c>Globals/LmagItm.dbf</c>, пятнадцать строк
/// (<c>0 L_ARMOR … 14 L_SPECIAL</c>, значения идут подряд). Тот же перечень лежит в коде движка
/// массивом имён по <c>0x7ab818</c>, и разбирающая его процедура (<c>0x585a9c</c>–<c>0x585c0b</c>)
/// заполняет пятнадцать глобальных категорий <b>в том же порядке</b>, что и строки таблицы, — то
/// есть привязка «имя → номер» проверена дважды, независимо.</para>
///
/// <para><b>Ранг 1: категория — это класс, а не подпись.</b> Фабрика предметов (<c>0x58329c</c>)
/// читает <c>ITEM_CAT</c>, сравнивает с этими пятнадцатью категориями и на каждую <b>строит свой
/// класс</b> — пятнадцать разных конструкторов, четыре разных размера объекта. Отсюда и таблица
/// ниже: какие колонки предмет несёт, решает не догадка, а то, какой конструктор его читает.</para>
///
/// <list type="table">
/// <item><term>0 Armor (7), 1 Jewel (8), 2 Weapon (16), 3 Banner (11), 13 TravelItem (5)</term>
///   <description>один конструктор <c>0x59c98d</c>: <c>MOD_EQUIP</c> в поле <c>+0x10</c>,
///   <c>ATTACK_ID</c> в <c>+0x14</c>. В ванили <c>MOD_EQUIP</c> заполнен у 41 из 47, и все шесть
///   оставшихся — оружие с <c>ATTACK_ID</c>: слоты взаимоисключающи по данным, но не по коду.</description></item>
/// <item><term>4 PotionBoost (15), 7 PotionPermanent (5)</term>
///   <description>конструктор <c>0x59d3d1</c>: <c>MOD_POTION</c> — все 20 ссылок ванили</description></item>
/// <item><term>5 PotionHeal (3)</term><description>конструктор <c>0x59d665</c>: <c>HP_POTION</c>
///   обычным читателем целого <c>0x5959f1</c> (границы <c>0x80000000..0x7fffffff</c>, без таблицы
///   категорий) — то есть величина, а не идентификатор. В ванили ровно три значения: 50, 100, 200</description></item>
/// <item><term>6 PotionRevive (1)</term><description>конструктор <c>0x59d7af</c> — только база,
///   своей колонки у воскрешения нет вовсе: что оно делает, задаёт категория</description></item>
/// <item><term>8 Scroll (120)</term><description>конструктор <c>0x59d08e</c>: <c>SPELL_ID</c></description></item>
/// <item><term>9 Wand (21)</term><description>тот же <c>0x59d08e</c> плюс <c>CASTING</c> банковым
///   читателем <c>0x595adf</c> (<c>0x59d2ed</c>) — свиток одноразов и бесплатен в применении,
///   жезл платит ману за каждое</description></item>
/// <item><term>10 Valuable (10), 14 Special (30)</term><description>только база
///   (<c>0x59c8fb</c>, <c>0x59c944</c>) — ни одной колонки полезной нагрузки</description></item>
/// <item><term>11 Orb (43), 12 Talisman (41)</term><description>конструктор <c>0x59ce2f</c>:
///   <c>ATTACK_ID</c> в <c>+0x10</c>, <c>MOD_EQUIP</c> в <c>+0x14</c> — те же два слота, что у
///   экипировки, но в обратном порядке полей. В ванили заполнен только <c>ATTACK_ID</c>,
///   все 84</description></item>
/// </list>
///
/// <para><b>Что это опровергает.</b> Постановка задачи знала пять видов предмета
/// («экипировка, зелья, свитки и сферы, предметы-атаки, призыв») и вешала призыв на
/// <c>UNIT_ID</c>. Категорий пятнадцать, а <b>предметов-призывов в ванили нет ни одного</b>:
/// <c>UNIT_ID</c> — поле <b>базовой</b> записи, его читает общий конструктор <see cref="Item.UnitId"/>,
/// и с призывом оно не связано.</para></summary>
public enum ItemCategory
{
    Armor = 0,
    Jewel = 1,
    Weapon = 2,
    Banner = 3,
    PotionBoost = 4,
    PotionHeal = 5,
    PotionRevive = 6,
    PotionPermanent = 7,
    Scroll = 8,
    Wand = 9,
    Valuable = 10,
    Orb = 11,
    Talisman = 12,
    TravelItem = 13,
    Special = 14,
}

/// <summary>Предмет — строка <c>GItem.DBF</c> глазами правил.
///
/// <para><b>Предмет кладёт эффект той же цепочкой, что заклинание и вард</b> — модификатором поверх
/// базового юнита (<c>D2.Rules.Units.EffectiveStats</c>, задача 2). Своего механизма у предмета
/// нет: <see cref="EquipModifierId"/> и <see cref="PotionModifierId"/> ведут в тот же
/// <c>Gmodif</c>/<c>GmodifL</c>, что <c>Gspells.MODIF_ID</c> и <c>Gattacks.WARD1..4</c>.</para>
///
/// <para><b>Раскладка базовой записи</b> (ранг 1, конструктор <c>CItemBase</c> <c>0x5a6bdc</c>,
/// прочитан до <c>ret</c>): <c>ITEM_ID</c> читается идентификаторным читателем <c>0x595a5a</c> в
/// собственное поле объекта, остальное — в общий блок данных на 32 байта:
/// <c>NAME_TXT +0</c>, <c>DESC_TXT +8</c>, <c>VALUE +0x10</c> (банковый читатель <c>0x595adf</c>),
/// <c>UNIT_ID +0x1c</c>. Совпадает с <c>CItemBaseData</c> тулсета поле в поле — чужой реверс здесь
/// подтверждение, а не источник.</para>
///
/// <para><b>Пустая ссылка — <c>g000000000</c>.</b> Перед чтением каждого необязательного
/// идентификатора конструкторы кладут в поле пустой id из <c>[0x6e7618]</c>
/// (<c>0x59c9ba</c>, <c>0x59ce5c</c>, <c>0x59d0ba</c>, <c>0x59d3fd</c>) — то есть «ссылки нет» и
/// «ссылка не разобралась» в движке различаются так же, как у нас: пустая строка против исключения.</para>
///
/// <para><c>NAME_TXT</c>, <c>DESC_TXT</c> и <c>IMAGE_ID</c> сюда не взяты: это тексты и картинка
/// для игрока, правилам они не нужны.</para></summary>
/// <param name="Value">Цена предмета — <b>та же строковая казна</b>, что у заклинания и постройки
/// (читатель <c>0x595adf</c>, грамматика разобрана задачей 9). <b>Ранг 1 по распределению:</b> все
/// 336 строк длиной 29 (пять валют, шестой — маны рощи — в цене предмета нет), ненулевой бывает
/// <b>только</b> золотая часть (306 строк), а 30 строк с нулевой ценой — ровно все
/// <see cref="ItemCategory.Special"/>: сюжетные предметы не продаются.</param>
/// <param name="CastingCost">Цена одного применения жезла — <c>CASTING</c>, тот же банковый
/// читатель. <b>Ранг 1 по распределению:</b> непуста ровно у 21 строки — всех
/// <see cref="ItemCategory.Wand"/>; 18 длиной 29 и <b>3 длиной 35</b> (шестая валюта, мана рощи —
/// ровно то ветвление <c>0x58637c</c> «читать <c>B</c> только если длина больше 29», что задача 9
/// прочла на цене заклинания); золота нет ни разу. У остальных 315 предметов колонка пуста, и
/// <see cref="Bank.Zero"/> здесь значит «применение ничего не стоит», а не «бесплатно по ошибке».
/// <para><b>Своя колонка, а не копия заклинания:</b> у 19 жезлов из 21 цена совпадает с
/// <c>Gspells.CASTING_C</c> их заклинания, а у двух — нет (<c>G000IG6016</c> берёт 200/200/400 при
/// 150/150/300 у «Armageddon», <c>G000IG6018</c> платит инфернальной вместо жизни). Выводить цену
/// жезла из заклинания нельзя.</para></param>
/// <param name="HealHitPoints">Сколько HP возвращает лечебное зелье — <c>HP_POTION</c>. Ранг 1:
/// читается обычным читателем целого без границ и без таблицы категорий, ненулевых значений в
/// ванили три — 50, 100, 200, и все три у <see cref="ItemCategory.PotionHeal"/>.</param>
/// <param name="UnitId">Юнит из базовой записи предмета (<c>CItemBaseData +0x1c</c>).
/// <b>Это не призыв</b> — постановка задачи называла так, и данные это опровергают (ранг 1):
/// поле не принадлежит какой-то одной категории, а лежит в <b>общей</b> базе всех предметов;
/// заполнено оно у 108 строк — четыре категории зелий (24) плюс сферы и талисманы (84), то есть
/// ровно у тех предметов, что применяются <b>в бою</b>; различных юнитов всего 25, и все 108
/// ссылок разрешаются в <c>Gunits</c>. Кто именно: лечебные зелья ссылаются на Priest
/// (<c>g000uu0012</c>), зелье воскрешения — на Hierophant (<c>g000uu0150</c>), зелья усиления — на
/// Alchemist (<c>g000uu0161</c>), сферы — на Elementalist (<c>g000uu0153</c>), то есть на юнитов,
/// чьё умение предмет изображает.
/// <para><b>Ранг 3 — что движок этим полем выбирает</b> (вид применения, анимация, лицо в бою).
/// Известно только, чем оно <b>не</b> является: боевая атака предмета берётся из
/// <see cref="AttackId"/>, а не отсюда (<c>getItemAttack</c> <c>0x6449b2</c> → <c>0x644a8e</c>
/// идёт от предмета к <c>Gattacks</c> напрямую, <c>UNIT_ID</c> в этом пути не участвует). Поэтому
/// поле <b>перенесено, но не смоделировано</b>. Снимет: прогон задачи 13 с применением сферы и
/// лечебного зелья в бою — если <c>UNIT_ID</c> ни на одно число журнала не влияет, оно
/// представление, а не правило.</para></param>
public sealed record Item(
    string Id,
    ItemCategory Category,
    Bank Value,
    string EquipModifierId,
    string PotionModifierId,
    int HealHitPoints,
    string SpellId,
    Bank CastingCost,
    string AttackId,
    string UnitId)
{
    /// <summary>Зелье ли это. <b>Ранг 1:</b> у движка есть ровно эта проверка отдельной процедурой
    /// (<c>0x5df8e8</c>) — категория сравнивается с четырьмя глобальными категориями
    /// <see cref="ItemCategory.PotionBoost"/>, <see cref="ItemCategory.PotionHeal"/>,
    /// <see cref="ItemCategory.PotionRevive"/>, <see cref="ItemCategory.PotionPermanent"/>, и
    /// ничего другого зельем не считается. Именно она стоит за отказом
    /// <see cref="PotionResult.NotAPotion"/>.</summary>
    public bool IsPotion => Category is ItemCategory.PotionBoost or ItemCategory.PotionHeal
                                      or ItemCategory.PotionRevive or ItemCategory.PotionPermanent;

    /// <summary>Пропадает ли надетый предмет по окончании боя.
    /// <para><b>Ранг 1:</b> <c>checkAndDestroyEquippedBattleItems</c> (Gog <c>0x629755</c>) обходит
    /// два слота снаряжения обоих предводителей и зовёт <c>0x629824</c>. Там категория сравнивается
    /// по очереди с <see cref="ItemCategory.Orb"/> и четырьмя зельями: совпало — предмет снимается и
    /// уничтожается (<c>0x5e746d</c> + <c>0x5e737d</c>). Отдельной веткой идёт
    /// <see cref="ItemCategory.Talisman"/>: он уничтожается <b>только</b> когда у него кончились
    /// заряды. <c>0x5eb9b3</c> возвращает <b>остаток зарядов</b> из списка <c>CMidTalismanCharges</c>:
    /// ищет запись по id через <c>0x5eba2a</c> и отдаёт поле <c>+4</c> — то самое, которое
    /// <c>0x5ebb30</c> уменьшает (<c>sub [eax+4], ecx</c>) и которое создание талисмана заполняет
    /// пятёркой из <c>[0x6ea178]</c> (<c>GVars.TALIS_CHRG</c> = 5); ветка <c>jge</c> на
    /// <c>0x6299f4</c> оставляет талисман жить. Прежнее прочтение «счёт одинаковых вещей в
    /// инвентаре» было ошибкой — поправлено 11.09.2026 дизассемблированием и живым сохранением M8
    /// (после боя с применением заряды 5 → 4). Это и есть механическая разница сферы и талисмана —
    /// по данным они неотличимы: один конструктор, одни колонки, у обоих только
    /// <c>ATTACK_ID</c>.</para>
    /// <para>Талисман здесь честно даёт <c>false</c> при любом <paramref name="applied"/>: его
    /// судьбу решает остаток зарядов — <see cref="Charges.TalismanAfterBattle"/> (задача 10).</para>
    /// <para><b>«Только применённый» — ранг 1 по наблюдению (задача 10).</b> Разбор кода этого не
    /// показывал: перечень категорий в <c>0x629824</c> безусловен. Прогон <c>f7-m17-charges</c>
    /// показал обратное: сфер было две, после боя, в котором сфера лежала в слоте и не применялась,
    /// осталось две, и только применения убрали их по одной (<c>item_unequip</c> слота 3 прямо на
    /// <c>battle_end</c> обоих боёв, П§18). Поэтому признак — параметр: предмет исчезает от
    /// применения, а не от надевания.</para>
    /// <para><b>Зелья — ранг 1</b> (отчёт B синтетических карт, ai-q33 и ai-q37): выпитые в бою
    /// уничтожаются в конце боя, в том числе проигранного (5/0), невыпитые остаются (16/0). Питьё —
    /// <c>BattleSim.DrinkPotion</c>.</para></summary>
    /// <param name="applied">Предмет в этом бою применяли — удар его атакой по цели
    /// (<c>BattleSim.UseBattleItem</c>). Построение атаки (<c>attack_new</c> с <c>impl</c> вида
    /// <c>IM…</c>) применением не является — <see cref="Charges"/>.</param>
    public bool IsDestroyedAfterBattle(bool applied) =>
        applied && (IsPotion || Category is ItemCategory.Orb);
}
