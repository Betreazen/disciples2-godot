        {
            if (open is not { } x) return;
            open = null;
            // Шаги по клеткам до первого скачка (дальше движок возвращает отряд на старт и ставит в конец одним ходом). Старт отряда в
            // крепости — её вход, а возвращается он на записанную клетку — угол крепости (0x440284 после проверки): у конца пути рядом с
