    /// уровню. Остаток: движок иногда встаёт раньше с запасом (у локаций сценария и рядом с неразобранными
    /// объектами), тай-брейк A* в 1–2 клетках пути, помощники идут за лидером, который у порта стоит иначе.
    /// Не подгонять. Найм лидеров из журнала при любой казне порта (23.09): перемещений human 625 → 633, legions 733 → 737.
    /// 24.09: нанятый лидер ходит в тот же день с полным запасом, первый шаг из ворот крепости бесплатен
