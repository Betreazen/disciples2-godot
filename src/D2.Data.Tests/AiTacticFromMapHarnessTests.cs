            {
                case AiTurnEvent { Phase: "begin" } t:
                    // В журнале с двумя картами (probe65) — только карта mapPrefix.
                    if (mapPrefix.Length > 0 && t.Player is not null && !t.Player.StartsWith(mapPrefix, StringComparison.OrdinalIgnoreCase))
