            var prev = x.Start;
            var home = x.Map.Stacks.TryGetValue(x.Stack, out var homeStack) ? (homeStack.X, homeStack.Y) : x.Start;
            foreach (var c in x.Steps)
            {
                if (Math.Max(Math.Abs(c.X - prev.X), Math.Abs(c.Y - prev.Y)) != 1 || c == x.Start || c == home) break;
                walked.Add(c);
                prev = c;
            }
            var end = x.Steps.Count == 0 ? x.Start : x.Steps[^1];
            // Вход в крепость: последняя stack_move — угол крепости, а не вход, по которому шли.
            if (walked.Count > 0 && x.Map.Sites.Any(f => f.Kind is SiteKind.Capital or SiteKind.Village && (f.X, f.Y) == end)) end = walked[^1];
            var portEnd = x.Port.Count == 0 ? x.Start : x.Port[^1];
            string cls = $"{x.Vft} {(AiActionType)x.Type}";
            if (x.Vft != MoveClass)
            {
