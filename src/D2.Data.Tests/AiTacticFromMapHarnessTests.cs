                        open = null;
                        break;
                    }
                    // Переигранный день (тот же игрок начинает тот же день снова — загрузка сохранения): живой день — заново.
                    bool replay = live is not null && live.Day == t.Turn && !begun.Add(t.Player ?? "");
                    if (live is null || live.Day != t.Turn || replay)
                    {
                        begun.Clear();
                        begun.Add(t.Player ?? "");
                        open = null;
                        live = DaySave(journal, saves, stem, (int)t.Turn, t.Seq) is { } sg
                            ? new AiLiveDay(MapLooksLoader.Load(sg), (int)t.Turn, content.MapArt, book, spends, EventLoader.Load(sg))
                            : null;
                    }
                    if (t.Player is not null && live is not null)
                    {
                        live.BeginTurn(t, hiresOfTurn.GetValueOrDefault(t.Seq), pathCrt);
                        var map = live.Session().Map;
                        foreach (var (sid, left) in dayStart.Where(d => map.Stacks.TryGetValue(d.Key, out var st) && Same(st.Owner, t.Player)))
                        {
                            var st = map.Stacks[sid];
                            Count(tally, st.Move == left ? "запас начала хода сошёлся" : $"запас начала хода: порт {st.Move}, движок {left}");
                            if (st.Move != left && shownStart++ < 10)
                                output.WriteLine($"запас {sid}: порт {st.Move}, движок {left}; лидер {map.Units[st.LeaderId].TypeId} мод [{string.Join(",", map.Units[st.LeaderId].Modifiers)}] предметы [{string.Join(",", st.Items.Select(i => map.ItemTypes.GetValueOrDefault(i, i)))}]");
                            live.MoveLeft(sid, left);
                        }
                        dayStart.Clear();
                    }
                    break;
                case ApRestoreEvent { Ret: true, Cause: "turn_start" } ap:
                    dayStart[ap.Stack] = (int)ap.MoveAfter;
                    break;
                case AiTacticPickEvent { PhaseBefore: 4, Chosen: [{ Action: { Type: { } type, Stack: { } sid, Point: { } p } a }, ..] } pick
                    when live is not null:
                {
                    var session = live.Session();
                    if (!session.Map.Stacks.TryGetValue(sid, out var stack)) break;
                    var start = PathFinder.Start(session.Map, stack);
                    // Классы, что не ходят (действие с соседней клетки, «стоять», «ждать»), — ноль шагов.
                    var path = a.Vft == MoveClass
                        ? AiTactics.Route(session, stack, new AiTacticOption((AiActionType)type, sid, a.Target ?? "", (int)p.X, (int)p.Y))
                        : StackPath.Empty;
                    // Упреждающая проверка пути событиями (0x440284): отряд встаёт там, где сработало бы событие.
                    int walk = session.PathEvents(sid, path.Today).Walk;
                    open = new Exec(sid, (int)type, a.Vft, ((int)p.X, (int)p.Y), start, stack.Move, pick.SeqEnd,
                                    [.. path.Today.Take(walk).Select(c => (c.X, c.Y))], [], [.. path.Points.Skip(1).Select(c => (c.X, c.Y))], session.Map, [.. path.Points.Skip(1).Select(c => c.Cost)]);
                    break;
                }
                case AiTacticResultEvent r:
                    if (open is not null && Same(r.Stack, open.Stack)) Close(r.Status);
                    if (rodBreaker is { } rb && Same(rb, r.Stack) && live is not null && r.Target is { Length: > 0 } rodId)
                        live.BreakRod(rodId, rb);
                    rodBreaker = null;
                    // Мешок, подобранный с соседней клетки (класс 0x6d21f4, без шага), — снять с карты живого дня: иначе путь порта
                    // обрывается перед мешком, которого у движка уже нет (0x5cda67: мешок в клетке — стоп).
                    if (r.Status is AiTactic.StatusProgress or 2 && live is not null && r.Target is { Length: > 0 } bagId && (r.Status == 2 || live.Reached(bagId, r.Stack)))
                        live.TakeBag(bagId, r.Stack);
                    break;
                case StackMoveEvent m when live is not null:
                    if (open is not null && Same(m.Stack, open.Stack) && m.Seq < open.SeqEnd) open.Steps.Add(((int)m.X, (int)m.Y));
                    live.Move(m.Stack, (int)m.X, (int)m.Y, (int)m.MoveLeft);
                    break;
                case AiOrderEvent o when live is not null:
                    live.Order(o);
                    break;
                case SpellCastEvent sc when live is not null:
                    live.Cast(sc);
                    break;
                case HireLeaderEvent hl when live is not null:
                    live.HireLeader(hl);
                    break;
                case IdAllocEvent ia when live is not null:
                    live.IdAlloc(ia);
                    break;
                case BattleEndEvent b when live is not null:
                    live.Battle(b);
                    foreach (var x in battleXp) live.Xp(x);
                    battleXp.Clear();
                    break;
                case XpEvent x when x.RetAddr != AiLiveDay.DailyXpCheat:
                    battleXp.Add(x);
                    break;
                case HealEvent { Ret: true } h when live is not null:
                    live.Heal(h.Unit);
                    break;
                case HpChangeEvent { Ret: true } hc when live is not null:
                    live.Hp(hc.Unit, (int)hc.HpAfter);
                    break;
                case ReviveEvent { Ret: true, HpAfter: { } hpAfter } rv when live is not null:
                    live.Hp(rv.Unit, (int)hpAfter);
                    break;
                case FortCaptureEvent fc when live is not null:
                    live.Capture(fc);
                    live.MoveEvents(fc.Stack);   // события после хода захватчика (разовые — выполнены, как у движка)
                    break;
                case RodDropEvent rd when live is not null:
                    live.Rod(rd);
                    break;
                // Сумку этот харнесс не сверяет — у зелья важно только здоровье (флаг «лидер жив» и цена шага).
                case PotionUseEvent { Ret: true, InBattle: false } pu when live is not null:
                    live.Hp(pu.Target, (int)pu.HpAfter);
                    break;
                case ApRestoreEvent { Ret: true } ap when live is not null && ap.Cause is not ("stack_move" or "turn_start"):
                    live.MoveLeft(ap.Stack, (int)ap.MoveAfter);
                    if (ap.Cause == "rod_break") rodBreaker = ap.Stack;
                    break;
                case ApRestoreEvent { Ret: true, Cause: "stack_move" } ap when open is not null && Same(ap.Stack, open.Stack):
                    open.Spent.Add((int)ap.Amount);
                    break;
                // Мешок, взятый с соседней клетки без строки подбора, и вор, погибший на деле, — как в LiveDayReplay (PathExpandHarnessTests).
                case EquipCheckEvent q when live is not null:
                    live.BagItemSeen(q.Stack, q.Item);
                    break;
                case NobleActionEvent na when live is not null:
                    live.Noble(na);
                    break;
                case AllianceChangeEvent ac when live is not null && ac.Ret:
                    live.Alliance(ac);   // разрыв посреди дня — зона контроля бывших союзников (карта 22, день 10)
                    break;
            }
        foreach (var (k, n) in tally) output.WriteLine($"{k}: {n}");
        int moves = tally.Where(t => t.Key is "да" or "конец" or "форма нет" or "форма, длина нет").Sum(t => t.Value);
        // −1 — числа новой партии не закреплены (карта 23): путь целиком у всех исполнений.
        if (wantAllowance >= 0) Assert.Equal(wantAllowance, tally.GetValueOrDefault("запас начала хода сошёлся"));
        Assert.DoesNotContain(tally.Keys, k => k.StartsWith("запас начала хода: ", StringComparison.Ordinal));
        if (wantMoves >= 0) Assert.Equal(wantMoves, moves);
        Assert.Equal(wantPath >= 0 ? wantPath : moves, tally.GetValueOrDefault("да"));
        Assert.Equal(wantEndOnly, tally.GetValueOrDefault("конец"));
    }

    /// <summary>Сохранение, с которого живой день начинается в строке <paramref name="seq"/>: последнее из записанных журналом
    /// (<c>save</c>, привязка файлов — <see cref="CheckJournal"/>) в тот же день до неё. Последнее сохранение дня по номеру файла — неверно
    /// для дня, переигранного загрузкой: human день 23 (пять копий, 040–044) — второй проход идёт с автосохранения seq 5417667 после
    /// загрузки, а последняя копия снята в первом проходе (S073KC0075 уже ушёл с (85,47) на (82,46), вор KC0089 обходил его зону
    /// контроля). Привязки нет — последнее сохранение дня, как прежде.</summary>
    internal static string? DaySave(string journal, IReadOnlyDictionary<int, string> saves, string stem, int day, long seq) =>
        CheckJournal.Load(journal).Saves
            .LastOrDefault(c => c.Turn == day && c.Seq < seq && Path.GetFileName(c.Path).StartsWith(stem, StringComparison.OrdinalIgnoreCase))?.Path
        ?? saves.GetValueOrDefault(day);

    /// <summary>Шпионаж журнала по дням (<c>noble_action</c> 1): день → игрок → кого он разведывал.</summary>
    internal static Dictionary<int, IReadOnlyDictionary<string, IReadOnlySet<string>>> SpiedByDay(IEnumerable<CorpusEvent> events)
    {
        var byDay = new Dictionary<int, Dictionary<string, HashSet<string>>>();
        int day = 0;
        foreach (var e in events)
            switch (e)
            {
                case AiTurnEvent { Phase: "begin", Turn: > 0 } t:
                    day = (int)t.Turn;
                    break;
                case NobleActionEvent { Action: (int)ThiefAction.Spy } n when n.Id.Length > 0:
                    if (!byDay.TryGetValue(day, out var players)) byDay[day] = players = new(StringComparer.OrdinalIgnoreCase);
                    if (!players.TryGetValue(n.Player, out var ids)) players[n.Player] = ids = new(StringComparer.OrdinalIgnoreCase);
                    ids.Add(n.Id);
                    break;
            }
        return byDay.ToDictionary(p => p.Key, p => (IReadOnlyDictionary<string, IReadOnlySet<string>>)p.Value.ToDictionary(
            q => q.Key, q => (IReadOnlySet<string>)q.Value, StringComparer.OrdinalIgnoreCase));
    }

    /// <summary>Разведанные игроки по сохранению дня (<see cref="MapPlayer.Spied"/>); нет сохранения — null.</summary>
    internal static IReadOnlyDictionary<string, IReadOnlyList<string>>? SpiedOf(IReadOnlyDictionary<int, string> saves, int day) =>
        saves.TryGetValue(day, out var sg)
            ? MapLoader.Load(sg).Players.Values.ToDictionary(p => p.Id, p => p.Spied, StringComparer.OrdinalIgnoreCase)
            : null;

