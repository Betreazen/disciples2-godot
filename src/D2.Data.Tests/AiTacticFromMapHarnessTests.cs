                                 $"движок [{string.Join(" ", walked.Select(c => $"{c.X},{c.Y}"))}] порт [{string.Join(" ", x.Port.Select(c => $"{c.X},{c.Y}"))}] | весь [{string.Join(" ", x.Full.Select(c => $"{c.X},{c.Y}"))}]" +
                                 $" | списал {string.Join(",", x.Spent)}, цены порта {string.Join(",", x.Costs)} | рядом: {Around(x.Map, end)}");
        }

        var pathCrt = JournalCrt.Of(journal);
        var hiresOfTurn = AiSpellHarnessTests.HiresOfTurns(events);
        foreach (var e in events)
