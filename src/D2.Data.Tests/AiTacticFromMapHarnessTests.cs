    /// обёртки), свободные клетки (<c>0x5f4485</c>) есть, отряд не в крепости (слот 4); своя крепость не в бунте (<c>0x5e9582</c>).
    /// Проверка игрока у столицы (<c>0x5e4e73</c>) не повторена. Боец и жезлоносец не «по воде» (списки <c>0x4633fe</c>,
    /// <c>0x463fd8</c>; у вора построителя нет).</summary>
    private static int HireForts(GameSession session, MapStack stack)
    {
        var map = session.Map;
        if (AiTactics.KindOf(session, stack) is not (AiStackKind.Fighter or AiStackKind.Rod) || session.WaterOnly(stack) || stack.Inside.Length > 0
            || session.FreeCells(stack) == 0
            || (map.Players.TryGetValue(stack.Owner, out var owner) && owner.CapturedBy.Length > 0)) return 0;
        return map.Sites.Count(f => f.Kind is SiteKind.Capital or SiteKind.Village && Same(f.Owner, stack.Owner) && !(f.Kind == SiteKind.Village && f.RiotTurn is > 0));
    }

